        <p><strong>Toma distancia y no respondas a las provocaciones.</strong> Un claxon, un grito o una mala maniobra no son un reto personal. Piensa si hay otra forma de ver la situación y deja pasar. En la calle, una reacción impulsiva puede tener consecuencias graves.</p>

        <p><strong>Guarda el celular y los audífonos.</strong> Distraerte reduce tu atención y aumenta el nerviosismo ante lo inesperado. Toma pausas digitales durante el trayecto para llegar atento y tranquilo.</p>
