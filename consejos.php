        <h2>Reconoce lo que sientes antes de reaccionar.</h2>

        <p>Si un conductor se cierra, el camión no te deja pasar o vas tarde, haz una pausa y nómbralo: ¿es enojo, prisa, miedo, nervios? Identificar la emoción evita que decida por ti.</p>

